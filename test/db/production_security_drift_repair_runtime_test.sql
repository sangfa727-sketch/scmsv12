DO $assert$
DECLARE
  result jsonb;
  internal_table text;
  browser_role text;
  privilege_name text;
  stale_count integer;
  audit_payload jsonb;
BEGIN
  FOREACH internal_table IN ARRAY ARRAY['app_sessions', 'audit_log', 'n8n_state'] LOOP
    FOREACH browser_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
      FOREACH privilege_name IN ARRAY ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER'] LOOP
        IF has_table_privilege(browser_role, format('public.%I', internal_table), privilege_name) THEN
          RAISE EXCEPTION 'browser role % retains % on public.%', browser_role, privilege_name, internal_table;
        END IF;
      END LOOP;
    END LOOP;
  END LOOP;

  IF has_function_privilege('anon', 'public.rpc_parent_google_login(text,text,text)', 'EXECUTE')
     OR has_function_privilege('authenticated', 'public.rpc_parent_google_login(text,text,text)', 'EXECUTE')
     OR NOT has_function_privilege('service_role', 'public.rpc_parent_google_login(text,text,text)', 'EXECUTE') THEN
    RAISE EXCEPTION 'Parent Login RPC grants are not restricted to the trusted service role';
  END IF;

  result := public.rpc_parent_google_login('qr-secret-a', 'PARENT@example.invalid', 'CI user-agent');
  IF COALESCE((result->>'ok')::boolean, false) IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'valid Parent Login failed: %', result;
  END IF;
  IF (result->'student') ?| ARRAY['qr_token', 'parent_email', 'school_id', 'status'] THEN
    RAISE EXCEPTION 'Parent Login returned non-allowlisted student fields: %', result->'student';
  END IF;
  IF result->'student'->>'student_id' IS DISTINCT FROM 'student-a'
     OR result->'student'->>'school_name' IS DISTINCT FROM 'School A' THEN
