-- Deterministic helper stub: the RPC function and tenant-bound queries below are real.
CREATE OR REPLACE FUNCTION private.web_has_permission(p_session_token text, p_permission text)
RETURNS boolean
LANGUAGE sql
STABLE
AS $fn$
  SELECT CASE
    WHEN p_session_token = 'no-permissions' AND p_permission = 'permissions.manage' THEN false
    WHEN p_session_token = 'no-view' AND p_permission = 'teachers.view' THEN false
    WHEN p_session_token = 'no-manage' AND p_permission = 'teachers.manage' THEN false
    ELSE true
  END;
$fn$;

