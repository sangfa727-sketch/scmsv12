     OR has_function_privilege('authenticated', 'public.rpc_parent_login_rate_limit(text,integer,integer)', 'EXECUTE')
     OR NOT has_function_privilege('service_role', 'public.rpc_parent_login_rate_limit(text,integer,integer)', 'EXECUTE') THEN
    RAISE EXCEPTION 'rate-limit RPC grants are not restricted to the trusted service role';
  END IF;

  result := public.rpc_parent_login_rate_limit(repeat('a', 64), 900, 2);
  IF result->>'allowed' IS DISTINCT FROM 'true' THEN RAISE EXCEPTION 'first rate-limit attempt denied: %', result; END IF;
  result := public.rpc_parent_login_rate_limit(repeat('a', 64), 900, 2);
  IF result->>'allowed' IS DISTINCT FROM 'true' THEN RAISE EXCEPTION 'second rate-limit attempt denied: %', result; END IF;
  result := public.rpc_parent_login_rate_limit(repeat('a', 64), 900, 2);
  IF result->>'allowed' IS DISTINCT FROM 'false' THEN RAISE EXCEPTION 'rate-limit threshold was not enforced: %', result; END IF;

  INSERT INTO private.parent_login_rate_limits(key_hash, window_started_at, attempts, updated_at)
  SELECT lpad(to_hex(gs), 64, '0'), now() - interval '25 hours', 1, now() - interval '25 hours'
    FROM generate_series(1, 1005) AS gs;
  PERFORM public.rpc_parent_login_rate_limit(repeat('b', 64), 900, 30);
  SELECT count(*) INTO stale_count
    FROM private.parent_login_rate_limits
