CREATE OR REPLACE FUNCTION extensions.gen_random_bytes(p_count integer)
RETURNS bytea LANGUAGE sql IMMUTABLE AS $crypto$
  SELECT decode(repeat('ab', greatest(p_count, 0)), 'hex');
$crypto$;
CREATE OR REPLACE FUNCTION extensions.digest(p_data text, p_type text)
RETURNS bytea LANGUAGE sql IMMUTABLE AS $crypto$
  SELECT decode(md5(p_data), 'hex');
$crypto$;

