-- SCMS v12 — Staff Chat project/event groups.
-- Restored from the live migration contract so a fresh database can reproduce
-- the Group Chat schema and RPC surface. Follow-up validation hardening lives
-- in 20261011120000_staff_project_event_group_member_validation.sql.

create table if not exists public.staff_project_event_groups (
  id bigint generated by default as identity primary key,
  school_id text not null,
  name text not null,
  description text,
  group_type text not null default 'PROJECT' check (group_type in ('PROJECT','EVENT')),
  status text not null default 'OPEN' check (status in ('OPEN','CLOSED')),
  created_by_teacher_id text not null,
  created_by_teacher_name text not null,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.staff_project_event_group_members (
  group_id bigint not null references public.staff_project_event_groups(id) on delete cascade,
  school_id text not null,
  teacher_id text not null,
  member_role text not null default 'MEMBER' check (member_role in ('OWNER','MEMBER')),
  last_read_at timestamptz not null default now(),
  added_at timestamptz not null default now(),
  primary key (group_id, teacher_id)
);

create table if not exists public.staff_project_event_group_messages (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.staff_project_event_groups(id) on delete cascade,
  school_id text not null,
  sender_teacher_id text not null,
  sender_teacher_name text not null,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index if not exists idx_speg_school_updated
  on public.staff_project_event_groups (school_id, updated_at desc);
create index if not exists idx_spegm_teacher
  on public.staff_project_event_group_members (teacher_id, school_id);
create index if not exists idx_spegmsg_group_created
  on public.staff_project_event_group_messages (group_id, created_at);

alter table public.staff_project_event_groups enable row level security;
alter table public.staff_project_event_group_members enable row level security;
alter table public.staff_project_event_group_messages enable row level security;
revoke all on public.staff_project_event_groups from anon, authenticated;
revoke all on public.staff_project_event_group_members from anon, authenticated;
revoke all on public.staff_project_event_group_messages from anon, authenticated;

create or replace function public.rpc_chat_group_create(
  p_session_token text,
  p_name text,
  p_description text default null,
  p_group_type text default 'PROJECT',
  p_starts_at timestamptz default null,
  p_ends_at timestamptz default null,
  p_member_teacher_ids jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v record;
  g_id bigint;
  member_id text;
begin
  select s.school_id,s.teacher_id,t.teacher_name,t.role into v
  from public.app_web_sessions s
  join public.teachers t on t.teacher_id=s.teacher_id
  where s.session_token=p_session_token and s.expires_at>now()
    and t.status='active' and t.school_id=s.school_id and t.role=s.role
  limit 1;
  if v is null then return jsonb_build_object('ok',false,'error','invalid_session'); end if;
  if nullif(trim(p_name),'') is null or char_length(trim(p_name))>160 then
    return jsonb_build_object('ok',false,'error','bad_name');
  end if;
  if p_group_type not in ('PROJECT','EVENT') then
    return jsonb_build_object('ok',false,'error','bad_group_type');
  end if;
  if p_ends_at is not null and p_starts_at is not null and p_ends_at<p_starts_at then
    return jsonb_build_object('ok',false,'error','bad_time_range');
  end if;

  insert into public.staff_project_event_groups(
    school_id,name,description,group_type,created_by_teacher_id,created_by_teacher_name,starts_at,ends_at
  ) values (
    v.school_id,trim(p_name),nullif(trim(p_description),''),p_group_type,
    v.teacher_id,v.teacher_name,p_starts_at,p_ends_at
  ) returning id into g_id;

  insert into public.staff_project_event_group_members(group_id,school_id,teacher_id,member_role)
  values(g_id,v.school_id,v.teacher_id,'OWNER');

  for member_id in select jsonb_array_elements_text(coalesce(p_member_teacher_ids,'[]'::jsonb)) loop
    if exists(
      select 1 from public.teachers t
      where t.teacher_id=member_id and t.school_id=v.school_id and t.status='active'
    ) and member_id<>v.teacher_id then
      insert into public.staff_project_event_group_members(group_id,school_id,teacher_id,member_role)
      values(g_id,v.school_id,member_id,'MEMBER') on conflict do nothing;
    end if;
  end loop;

  return jsonb_build_object('ok',true,'group_id',g_id);
end
$function$;

create or replace function public.rpc_chat_group_list(
  p_session_token text,
  p_group_type text default null,
  p_limit integer default 50
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v record;
  v_rows jsonb;
begin
  select s.school_id,s.teacher_id,t.teacher_name,t.role into v
  from public.app_web_sessions s join public.teachers t on t.teacher_id=s.teacher_id
  where s.session_token=p_session_token and s.expires_at>now()
    and t.status='active' and t.school_id=s.school_id and t.role=s.role
  limit 1;
  if v is null then return jsonb_build_object('ok',false,'error','invalid_session'); end if;

  select coalesce(jsonb_agg(to_jsonb(x) order by x.updated_at desc,x.id desc),'[]'::jsonb)
  into v_rows
  from (
    select g.*,
      (select count(*)::int
       from public.staff_project_event_group_messages m
       left join public.staff_project_event_group_members r
         on r.group_id=g.id and r.teacher_id=v.teacher_id
       where m.group_id=g.id and m.school_id=v.school_id
         and m.sender_teacher_id<>v.teacher_id
         and m.created_at>coalesce(r.last_read_at,'epoch'::timestamptz)
      ) unread_count,
      exists(
        select 1 from public.staff_project_event_group_members mm
        where mm.group_id=g.id and mm.teacher_id=v.teacher_id and mm.school_id=v.school_id
      ) is_member
    from public.staff_project_event_groups g
    where g.school_id=v.school_id and (p_group_type is null or g.group_type=p_group_type)
      and exists(
        select 1 from public.staff_project_event_group_members mm
        where mm.group_id=g.id and mm.teacher_id=v.teacher_id and mm.school_id=v.school_id
      )
    order by g.updated_at desc,g.id desc
    limit greatest(1,least(coalesce(p_limit,50),100))
  ) x;
  return jsonb_build_object('ok',true,'rows',v_rows);
end
$function$;

create or replace function public.rpc_chat_group_open(p_session_token text,p_group_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v record;
  g jsonb;
  msgs jsonb;
begin
  select s.school_id,s.teacher_id,t.teacher_name,t.role into v
  from public.app_web_sessions s join public.teachers t on t.teacher_id=s.teacher_id
  where s.session_token=p_session_token and s.expires_at>now()
    and t.status='active' and t.school_id=s.school_id and t.role=s.role
  limit 1;
  if v is null then return jsonb_build_object('ok',false,'error','invalid_session'); end if;
  if not exists(
    select 1 from public.staff_project_event_group_members m
    where m.group_id=p_group_id and m.school_id=v.school_id and m.teacher_id=v.teacher_id
  ) then return jsonb_build_object('ok',false,'error','group_forbidden'); end if;

  select to_jsonb(x) into g
  from (select * from public.staff_project_event_groups where id=p_group_id and school_id=v.school_id) x;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at asc),'[]'::jsonb) into msgs
  from (
    select * from public.staff_project_event_group_messages
    where group_id=p_group_id and school_id=v.school_id
    order by created_at desc limit 100
  ) x;
  return jsonb_build_object('ok',true,'group',g,'messages',msgs);
end
$function$;

create or replace function public.rpc_chat_group_send(p_session_token text,p_group_id bigint,p_body text)
returns jsonb
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v record;
  mid bigint;
begin
  select s.school_id,s.teacher_id,t.teacher_name,t.role into v
  from public.app_web_sessions s join public.teachers t on t.teacher_id=s.teacher_id
  where s.session_token=p_session_token and s.expires_at>now()
    and t.status='active' and t.school_id=s.school_id and t.role=s.role
  limit 1;
  if v is null then return jsonb_build_object('ok',false,'error','invalid_session'); end if;
  if not exists(
    select 1 from public.staff_project_event_group_members m
    where m.group_id=p_group_id and m.school_id=v.school_id and m.teacher_id=v.teacher_id
  ) then return jsonb_build_object('ok',false,'error','group_forbidden'); end if;
  if not exists(
    select 1 from public.staff_project_event_groups g
    where g.id=p_group_id and g.school_id=v.school_id and g.status='OPEN'
  ) then return jsonb_build_object('ok',false,'error','group_closed'); end if;
  if nullif(trim(p_body),'') is null or char_length(trim(p_body))>4000 then
    return jsonb_build_object('ok',false,'error','bad_body');
  end if;

  insert into public.staff_project_event_group_messages(
    group_id,school_id,sender_teacher_id,sender_teacher_name,body
  ) values(p_group_id,v.school_id,v.teacher_id,v.teacher_name,trim(p_body))
  returning id into mid;
  update public.staff_project_event_groups set updated_at=now() where id=p_group_id;
  return jsonb_build_object('ok',true,'message_id',mid);
end
$function$;

