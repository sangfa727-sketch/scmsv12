DO $assertions$
DECLARE
  v jsonb;
  v_count integer;
BEGIN
  -- A valid admin cannot read a teacher from another school.
  v := public.rpc_manage_teacher_access('admin-a-token','list','teacher-b',NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'teacher_not_found' THEN
    RAISE EXCEPTION 'Cross-school list must fail closed; got %', v;
  END IF;

  -- Cross-school writes must fail before any assignment or permission mutation.
  v := public.rpc_manage_teacher_access('admin-a-token','class_add','teacher-b','Grade B2',NULL,'class_teacher',NULL,NULL,NULL);
  IF v->>'error' <> 'teacher_not_found' THEN
    RAISE EXCEPTION 'Cross-school class assignment must fail closed; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('admin-a-token','subject_add','teacher-b','Grade B1',201,NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'teacher_not_found' THEN
    RAISE EXCEPTION 'Cross-school subject assignment must fail closed; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('admin-a-token','permission_set','teacher-b',NULL,NULL,NULL,'students.view',false,'global');
  IF v->>'error' <> 'teacher_not_found' THEN
    RAISE EXCEPTION 'Cross-school permission write must fail closed; got %', v;
  END IF;

  SELECT count(*) INTO v_count
    FROM public.teacher_class_assignments
   WHERE school_id='school-b' AND teacher_id='teacher-b';
  IF v_count <> 1 THEN
    RAISE EXCEPTION 'Cross-school class mutation changed School B rows; count=%', v_count;
  END IF;

  SELECT count(*) INTO v_count
    FROM public.teacher_permissions
   WHERE school_id='school-b' AND teacher_id='teacher-b' AND permission_key='students.view' AND allowed=true;
  IF v_count <> 1 THEN
    RAISE EXCEPTION 'Cross-school permission mutation changed School B rows; count=%', v_count;
  END IF;

  -- Catalogs must only include classes and subjects from the caller's school.
  v := public.rpc_manage_teacher_access('admin-a-token','catalog',NULL,NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'ok' <> 'true'
     OR (v->'classes')::text LIKE '%Grade B1%'
     OR (v->'subjects')::text LIKE '%School B Mathematics%' THEN
    RAISE EXCEPTION 'School A catalog leaked School B data; got %', v;
  END IF;

  -- Lower-tier admins cannot change a super_admin target.
  v := public.rpc_manage_teacher_access('admin-a-token','class_add','super-a','Grade A1',NULL,'class_teacher',NULL,NULL,NULL);
  IF v->>'error' <> 'insufficient_role' THEN
    RAISE EXCEPTION 'Admin must not mutate a super_admin target; got %', v;
  END IF;

  -- Permission gates must reject the correct action families before mutation.
  v := public.rpc_manage_teacher_access('no-permissions','catalog',NULL,NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'permission_denied' THEN
    RAISE EXCEPTION 'catalog must require permissions.manage; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('no-view','list','teacher-a',NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'permission_denied' THEN
    RAISE EXCEPTION 'list must require teachers.view; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('no-manage','class_add','teacher-a','Grade A1',NULL,'class_teacher',NULL,NULL,NULL);
  IF v->>'error' <> 'permission_denied' THEN
    RAISE EXCEPTION 'class_add must require teachers.manage; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('no-permissions','permission_set','teacher-a',NULL,NULL,NULL,'students.view',false,'global');
  IF v->>'error' <> 'permission_denied' THEN
    RAISE EXCEPTION 'permission_set must require permissions.manage; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('expired-token','list','teacher-a',NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'admin_required' THEN
    RAISE EXCEPTION 'Expired session must fail closed; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('teacher-a-token','list','teacher-a',NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'admin_required' THEN
    RAISE EXCEPTION 'Non-admin role must fail closed; got %', v;
  END IF;

  -- Positive controls prove the harness is not only testing denials.
  v := public.rpc_manage_teacher_access('admin-a-token','class_add','teacher-a','Grade A1',NULL,'class_teacher',NULL,NULL,NULL);
  IF v->>'ok' <> 'true' THEN
    RAISE EXCEPTION 'Same-school authorized class assignment should succeed; got %', v;
  END IF;

  v := public.rpc_manage_teacher_access('admin-a-token','permission_set','teacher-a',NULL,NULL,NULL,'students.view',false,'global');
  IF v->>'ok' <> 'true' THEN
    RAISE EXCEPTION 'Same-school authorized permission mutation should succeed; got %', v;
  END IF;

  RAISE NOTICE 'Manage Teacher/Access real-RPC tenant-isolation runtime tests passed.';
END
$assertions$;
