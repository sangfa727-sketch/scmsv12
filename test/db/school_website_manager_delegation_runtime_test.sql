do $test$
declare
  v jsonb;
  v_count bigint;
begin
  v := public.rpc_school_website_authorize('owner-session');
  if v->>'ok' is distinct from 'true' or v->>'authorized' is distinct from 'true'
     or v->>'school_id' is distinct from 'school-a' then
    raise exception 'owner authorization failed: %', v;
  end if;

  v := public.rpc_school_website_authorize('staff-session');
  if v->>'authorized' is distinct from 'false' then
    raise exception 'ungranted staff unexpectedly authorized: %', v;
  end if;

  v := public.rpc_school_website_authorize('expired-session');
  if v->>'authorized' is distinct from 'false' then
    raise exception 'expired session unexpectedly authorized: %', v;
  end if;

  v := public.rpc_school_website_set_manager('staff-session', 'staff-a', true);
  if v->>'ok' is distinct from 'false' or v->>'error' is distinct from 'admin_required' then
    raise exception 'ordinary staff unexpectedly delegated permission: %', v;
  end if;

  v := public.rpc_school_website_set_manager('owner-session', 'foreign-staff', true);
  if v->>'ok' is distinct from 'false' or v->>'error' is distinct from 'active_same_school_staff_required' then
    raise exception 'cross-school target was not rejected: %', v;
  end if;

  v := public.rpc_school_website_set_manager('owner-session', 'admin-a', true);
  if v->>'ok' is distinct from 'false' or v->>'error' is distinct from 'privileged_target_not_allowed' then
    raise exception 'privileged target was not rejected: %', v;
  end if;

  -- Simulate a legacy/corrupt cross-tenant key collision. The conflict path must
  -- not rewrite the row from school-b to school-a or report success.
  insert into public.teacher_permissions
    (school_id, teacher_id, permission_key, allowed, scope_type, class_name, subject_id)
  values ('school-b', 'staff-a', 'website.manage', false, 'global', null, null);
  v := public.rpc_school_website_set_manager('owner-session', 'staff-a', true);
  if v->>'ok' is distinct from 'false' or v->>'error' is distinct from 'permission_scope_conflict' then
    raise exception 'cross-tenant permission collision was not rejected: %', v;
  end if;
  if not exists (
    select 1 from public.teacher_permissions
    where school_id = 'school-b' and teacher_id = 'staff-a' and allowed = false
  ) then
    raise exception 'cross-tenant permission row was modified';
  end if;
  delete from public.teacher_permissions where school_id = 'school-b' and teacher_id = 'staff-a';

  v := public.rpc_school_website_set_manager('owner-session', 'staff-a', true);
  if v->>'ok' is distinct from 'true' or v->>'allowed' is distinct from 'true' then
    raise exception 'valid manager grant failed: %', v;
  end if;
  v := public.rpc_school_website_set_manager('owner-session', 'staff-a', true);
  if v->>'ok' is distinct from 'true' then
    raise exception 'idempotent manager grant failed: %', v;
  end if;
  select count(*) into v_count from public.teacher_permissions
    where school_id = 'school-a' and teacher_id = 'staff-a'
      and permission_key = 'website.manage' and scope_type = 'global';
  if v_count <> 1 then
    raise exception 'expected exactly one permission row after repeat grant, got %', v_count;
  end if;

  v := public.rpc_school_website_authorize('staff-session');
  if v->>'authorized' is distinct from 'true' or v->>'school_id' is distinct from 'school-a' then
    raise exception 'delegated staff was not authorized in the correct school: %', v;
  end if;
  v := public.rpc_school_website_authorize('foreign-session');
  if v->>'authorized' is distinct from 'false' then
    raise exception 'other-school staff inherited website permission: %', v;
  end if;

  v := public.rpc_school_website_set_manager('admin-session', 'staff-a', false);
  if v->>'ok' is distinct from 'true' or v->>'allowed' is distinct from 'false' then
    raise exception 'manager revoke failed: %', v;
  end if;
  v := public.rpc_school_website_authorize('staff-session');
  if v->>'authorized' is distinct from 'false' then
    raise exception 'revoked staff retained website access: %', v;
  end if;

  select count(*) into v_count from public.audit_log
    where action = 'website.manager_grant' and school_id = 'school-a';
  if v_count <> 2 then
    raise exception 'expected two grant audit events, got %', v_count;
  end if;
  select count(*) into v_count from public.audit_log
    where action = 'website.manager_revoke' and school_id = 'school-a';
  if v_count <> 1 then
    raise exception 'expected one revoke audit event, got %', v_count;
  end if;
end
$test$;

select 'School Website delegation runtime tests passed' as result;
