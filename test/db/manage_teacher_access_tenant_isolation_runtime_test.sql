DO $assertions$
DECLARE
  v jsonb;
  v_count integer;
BEGIN
  -- A school-A admin cannot read a school-B teacher.
  v := public.rpc_manage_teacher_access('token-a','list','b-teacher',NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'teacher_not_found' THEN
    RAISE EXCEPTION 'cross-school list must fail closed; got %', v;
  END IF;

  -- Cross-school assignment mutation must fail and leave no row behind.
  v := public.rpc_manage_teacher_access('token-a','class_add','b-teacher','B-G1',NULL,'class_teacher',NULL,NULL,NULL);
  IF v->>'error' <> 'teacher_not_found' THEN
    RAISE EXCEPTION 'cross-school class assignment must fail closed; got %', v;
  END IF;
  SELECT count(*) INTO v_count FROM public.teacher_class_assignments
   WHERE school_id='school-a' AND teacher_id='b-teacher';
  IF v_count <> 0 THEN RAISE EXCEPTION 'cross-school class assignment wrote data'; END IF;

  -- Cross-school permission mutation must fail and leave no row behind.
  v := public.rpc_manage_teacher_access('token-a','permission_set','b-teacher',NULL,NULL,NULL,'dashboard.view',true,NULL);
  IF v->>'error' <> 'teacher_not_found' THEN
    RAISE EXCEPTION 'cross-school permission mutation must fail closed; got %', v;
  END IF;
  SELECT count(*) INTO v_count FROM public.teacher_permissions
   WHERE school_id='school-a' AND teacher_id='b-teacher';
  IF v_count <> 0 THEN RAISE EXCEPTION 'cross-school permission mutation wrote data'; END IF;

  -- School-scoped catalog data must not leak the other school's class or subject.
  v := public.rpc_manage_teacher_access('token-a','catalog','a-teacher',NULL,NULL,NULL,NULL,NULL,NULL);
  IF v->>'ok' <> 'true' OR (v->'classes')::text LIKE '%B-G1%' OR (v->'subjects')::text LIKE '%B Mathematics%' THEN
    RAISE EXCEPTION 'catalog leaked cross-school data or failed: %', v;
  END IF;
  IF NOT ((v->'classes')::text LIKE '%A-G1%') OR NOT ((v->'subjects')::text LIKE '%A Mathematics%') THEN
    RAISE EXCEPTION 'catalog omitted same-school data: %', v;
  END IF;

  -- A lower-tier admin cannot mutate a super_admin target in the same school.
  v := public.rpc_manage_teacher_access('token-a','class_add','a-super','A-G1',NULL,'class_teacher',NULL,NULL,NULL);
  IF v->>'error' <> 'insufficient_role' THEN
    RAISE EXCEPTION 'admin must not manage super_admin target; got %', v;
  END IF;

  -- Same-school assignment write should succeed and persist.
  v := public.rpc_manage_teacher_access('token-a','class_add','a-teacher','A-G1',NULL,'class_teacher',NULL,NULL,NULL);
  IF v->>'ok' <> 'true' THEN RAISE EXCEPTION 'same-school assignment should succeed: %', v; END IF;
  SELECT count(*) INTO v_count FROM public.teacher_class_assignments
   WHERE school_id='school-a' AND teacher_id='a-teacher' AND class_name='A-G1' AND is_active;
  IF v_count <> 1 THEN RAISE EXCEPTION 'same-school assignment was not persisted'; END IF;

  -- A subject owned by school B cannot be assigned to a school-A teacher.
  v := public.rpc_manage_teacher_access('token-a','subject_add','a-teacher','A-G1',
    (SELECT id FROM public.subjects WHERE school_id='school-b' LIMIT 1),
    NULL,NULL,NULL,NULL);
  IF v->>'error' <> 'subject_not_found' THEN
    RAISE EXCEPTION 'cross-school subject must be rejected; got %', v;
  END IF;

  RAISE NOTICE 'Manage Teacher/Access real-RPC tenant-isolation tests passed.';
END
$assertions$;
