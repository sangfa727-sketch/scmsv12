CREATE OR REPLACE FUNCTION private.web_has_student_permission(
  p_session_token text, p_permission_key text, p_student_id text
) RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'pg_temp'
AS $function$
  SELECT EXISTS (
    SELECT 1
      FROM public.app_web_sessions AS s
      JOIN public.teachers AS t
        ON t.teacher_id = s.teacher_id
       AND t.school_id = s.school_id
       AND t.role = s.role
       AND t.status = 'active'
      JOIN public.schools AS sc
        ON sc.school_id = t.school_id
       AND sc.status = 'active'
      JOIN public.students AS st
        ON st.school_id = s.school_id
       AND st.student_id = p_student_id
     WHERE s.session_token = p_session_token
       AND s.expires_at > now()
       AND p_permission_key = 'students.edit'
  );
$function$;

