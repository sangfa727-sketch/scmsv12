-- Isolated runtime test for School Website manager authorization/delegation.
-- Disposable PostgreSQL only; this harness does not connect to SCMS production.
\set ON_ERROR_STOP on

create role anon nologin;
create role authenticated nologin;
create schema private;

create table public.teachers (
  teacher_id text primary key,
  school_id text not null,
  role text not null,
  status text not null
);
create table public.app_web_sessions (
  session_token text primary key,
  school_id text not null,
  teacher_id text not null,
  role text not null,
  expires_at timestamptz not null
);
create table public.permission_definitions (
  permission_key text primary key,
  category text not null,
  description text not null,
  scope_type text not null,
  is_sensitive boolean not null default false,
  is_active boolean not null default true,
  display_order integer not null default 0
);
create table public.role_permissions (
  role text not null,
  permission_key text not null references public.permission_definitions(permission_key),
  allowed boolean not null,
  primary key (role, permission_key)
);
create table public.teacher_permissions (
  id bigint generated by default as identity primary key,
  school_id text not null,
  teacher_id text not null,
  permission_key text not null references public.permission_definitions(permission_key),
  allowed boolean not null,
  scope_type text not null,
  class_name text,
  subject_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index teacher_permissions_scope_uq
  on public.teacher_permissions (
    teacher_id, permission_key, scope_type,
    coalesce(class_name, ''), coalesce(subject_id, 0)
  );
create table public.audit_log (
  id bigint generated by default as identity primary key,
  source text not null,
  actor text not null,
  action text not null,
  school_id text not null,
  payload jsonb not null,
  created_at timestamptz not null default now()
);

create or replace function private.web_has_permission(
  p_session_token text,
  p_permission_key text,
  p_class_name text default null,
  p_subject_id bigint default null
) returns boolean
language sql
security definer
set search_path = public, pg_temp
as $function$
  select coalesce(
    (
      select tp.allowed
      from public.app_web_sessions s
      join public.teachers t
        on t.teacher_id = s.teacher_id
       and t.school_id = s.school_id
       and t.role = s.role
       and t.status = 'active'
      join public.teacher_permissions tp
        on tp.school_id = s.school_id
       and tp.teacher_id = s.teacher_id
       and tp.permission_key = p_permission_key
       and tp.scope_type = 'global'
       and tp.class_name is null
       and tp.subject_id is null
      where s.session_token = p_session_token
        and s.expires_at > now()
      order by tp.updated_at desc, tp.id desc
      limit 1
    ),
    (
      select rp.allowed
      from public.app_web_sessions s
      join public.teachers t
        on t.teacher_id = s.teacher_id
       and t.school_id = s.school_id
       and t.role = s.role
       and t.status = 'active'
      join public.role_permissions rp
        on rp.role = s.role
       and rp.permission_key = p_permission_key
      where s.session_token = p_session_token
        and s.expires_at > now()
      limit 1
    ),
    false
  );
$function$;

